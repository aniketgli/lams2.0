import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';

/**
 * Downloads a table as a themed PDF file (no print dialog): navy title band,
 * navy header row, striped rows and "Page x of y" on every page.
 *
 * The built-in PDF fonts cover Latin text only, so other scripts (e.g. Hindi
 * names) should be left out of PDF columns; CSV downloads keep them.
 */

export interface PdfTableOptions {
  title: string;
  /** Small lines under the title (filters, generated time). */
  subtitle?: string[];
  headers: string[];
  rows: unknown[][];
  /** File name without extension. */
  fileName: string;
  landscape?: boolean;
  /** Relative column widths (same length as headers); omitted = automatic. */
  columnWidths?: number[];
  /** Header details; omitted parts come from setExportContext and the moment of download. */
  meta?: Partial<ReportMeta>;
}

/**
 * Every download (PDF and CSV) carries the same report header and footer:
 *   organization · report title · filters / period · generated on · generated by (name, biometric ID, role) ·
 *   number of records ... data ... end-of-report line and the "computer-generated" notice.
 * File names follow one pattern: WII_<Report>_<period or subject>_<YYYY-MM-DD_HHmm>.<ext>
 * The signed-in person and the organization name are set once by the app (setExportContext).
 */
export interface ExportContext {
  organization: string;
  /** "Name (biometric ID) · Role" of the person downloading. */
  generatedBy: string | null;
}

let context: ExportContext = { organization: 'Wildlife Institute of India', generatedBy: null };

/** Called by the app when the session or the organization name changes. */
export function setExportContext(next: Partial<ExportContext>): void {
  context = { ...context, ...next, organization: next.organization?.trim() || context.organization };
}

export interface ReportMeta {
  organization: string;
  generatedAt: Date;
  generatedBy: string | null;
  /** Number of data rows. */
  records: number;
}

export const PORTAL_NAME = 'WII Portal';
export const REPORT_NOTICE = 'Computer-generated report from the WII Portal. For official use only.';

const pad = (n: number) => String(n).padStart(2, '0');
const stampOf = (d: Date) => `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}_${pad(d.getHours())}${pad(d.getMinutes())}`;

/**
 * The standard file name (without extension): WII_ prefix, only letters / digits / - / _, and the moment of
 * download, so two downloads never overwrite each other and the file tells when it was made.
 */
export function reportFileName(base: string, at: Date = new Date()): string {
  const cleaned = String(base ?? '').normalize('NFKD').replace(/[^\w-]+/g, '_').replace(/_+/g, '_').replace(/^_|_$/g, '') || 'Report';
  const withPrefix = /^WII_/i.test(cleaned) ? cleaned.replace(/^wii_/i, 'WII_') : `WII_${cleaned}`;
  return `${withPrefix.slice(0, 120)}_${stampOf(at)}`;
}

/** "15 Nov 2026, 14:05" (24-hour, India). */
export function formatGeneratedAt(d: Date): string {
  return d.toLocaleString('en-IN', { day: '2-digit', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit', hour12: false, timeZone: 'Asia/Kolkata' });
}

function metaOf(records: number, meta?: Partial<ReportMeta>): ReportMeta {
  return {
    organization: meta?.organization || context.organization,
    generatedAt: meta?.generatedAt ?? new Date(),
    generatedBy: meta?.generatedBy !== undefined ? meta.generatedBy : context.generatedBy,
    records: meta?.records ?? records,
  };
}

const NAVY: [number, number, number] = [32, 64, 136]; // --color-primary #204088
const INK: [number, number, number] = [15, 23, 42];

/** Text the standard PDF fonts can draw: arrows become "->", unsupported characters are dropped. */
export function pdfText(value: unknown): string {
  if (value === null || value === undefined || value === '') return '—';
  return String(value)
    .replace(/→/g, '->')
    .replace(/[“”]/g, '"')
    .replace(/[‘’]/g, "'")
    .replace(/[^\x20-\x7E -ÿ–—•…\n]/g, '')
    .replace(/\s{2,}/g, ' ')
    .trim() || '—';
}

/** The themed PDF itself (no DOM needed, so the server can build the same file for scheduled emails). */
export function buildTablePdf({ title, subtitle = [], headers, rows, landscape = true, columnWidths, meta: given }: Omit<PdfTableOptions, 'fileName'>): jsPDF {
  const meta = metaOf(rows.length, given);
  const doc = new jsPDF({ orientation: landscape ? 'landscape' : 'portrait', unit: 'mm', format: 'a4' });
  doc.setProperties({ title: pdfText(title), subject: subtitle.map(pdfText).join(' | '), author: meta.generatedBy ? pdfText(meta.generatedBy) : PORTAL_NAME, creator: PORTAL_NAME });
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 12;

  // Header band: organization, report title, filters / period
  const bandHeight = 19 + subtitle.length * 4.5;
  doc.setFillColor(...INK);
  doc.roundedRect(margin, margin, pageWidth - margin * 2, bandHeight, 2, 2, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8);
  doc.setTextColor(203, 213, 225);
  doc.text(pdfText(meta.organization).toUpperCase(), margin + 5, margin + 6);
  doc.text(PORTAL_NAME, pageWidth - margin - 5, margin + 6, { align: 'right' });
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(13);
  doc.text(pdfText(title), margin + 5, margin + 13);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(203, 213, 225);
  subtitle.forEach((line, i) => doc.text(pdfText(line), margin + 5, margin + 18.5 + i * 4.5));

  // Report details line under the band
  const detailsY = margin + bandHeight + 5;
  doc.setFontSize(7.5);
  doc.setTextColor(71, 85, 105);
  const details = [
    `Generated on: ${formatGeneratedAt(meta.generatedAt)}`,
    meta.generatedBy ? `Generated by: ${meta.generatedBy}` : null,
    `Records: ${meta.records}`,
  ].filter(Boolean).join('     |     ');
  doc.text(pdfText(details), margin, detailsY);

  const usable = pageWidth - margin * 2;
  const total = columnWidths?.reduce((a, b) => a + b, 0) ?? 0;
  const columnStyles = columnWidths && total > 0
    ? Object.fromEntries(columnWidths.map((w, i) => [i, { cellWidth: (w / total) * usable }]))
    : undefined;

  const footer = () => {
    doc.setDrawColor(203, 213, 225);
    doc.line(margin, pageHeight - 11, pageWidth - margin, pageHeight - 11);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7);
    doc.setTextColor(100, 116, 139);
    doc.text(pdfText(`${meta.organization} · ${PORTAL_NAME} · ${title}`), margin, pageHeight - 7);
    doc.text(pdfText(REPORT_NOTICE), pageWidth / 2, pageHeight - 7, { align: 'center' });
  };

  autoTable(doc, {
    startY: detailsY + 3,
    margin: { left: margin, right: margin, bottom: 15, top: margin },
    head: [headers.map(pdfText)],
    body: rows.length ? rows.map((r) => r.map(pdfText)) : [[{ content: 'No records.', colSpan: headers.length, styles: { halign: 'center' as const, textColor: [148, 163, 184] as [number, number, number] } }]],
    theme: 'grid',
    showHead: 'everyPage',
    styles: { font: 'helvetica', fontSize: 8, cellPadding: 2, textColor: INK, lineColor: [226, 232, 240], lineWidth: 0.2, overflow: 'linebreak', valign: 'top' },
    headStyles: { fillColor: NAVY, textColor: [255, 255, 255], fontStyle: 'bold', fontSize: 7.5 },
    alternateRowStyles: { fillColor: [248, 250, 252] },
    columnStyles,
    didDrawPage: footer,
  });

  // End-of-report line after the table, then "Page x of y" now that the total is known.
  const lastY = (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? detailsY;
  if (lastY + 8 < pageHeight - 15) {
    doc.setFontSize(7.5);
    doc.setTextColor(100, 116, 139);
    doc.text(`End of report · ${meta.records} record${meta.records === 1 ? '' : 's'}`, pageWidth / 2, lastY + 6, { align: 'center' });
  }
  const pages = doc.getNumberOfPages();
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i);
    doc.setFontSize(7);
    doc.setTextColor(100, 116, 139);
    doc.text(`Page ${i} of ${pages}`, pageWidth - margin, pageHeight - 7, { align: 'right' });
  }

  return doc;
}

export function downloadTablePdf(options: PdfTableOptions): void {
  buildTablePdf(options).save(`${reportFileName(options.fileName)}.pdf`);
}

/** "30 Oct 2026, 11:05" in the viewer's locale. */
export function printedAt(iso: string): string {
  const d = new Date(iso);
  return Number.isNaN(d.getTime()) ? iso : d.toLocaleString('en-IN', { day: '2-digit', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit', hour12: false });
}

/** What goes above and below the table in a CSV report. */
export interface CsvReportInfo {
  title: string;
  /** Period, filters, subject: one line each. */
  subtitle?: string[];
  meta?: Partial<ReportMeta>;
}

/**
 * Saves CSV text as a file (UTF-8 with BOM so Excel shows names correctly), named by reportFileName.
 * With `report`, the standard header (organization, report, filters, generated on / by, records) and
 * footer are added around the table. Import templates are saved without them (pass no `report`).
 */
export function downloadCsvText(csv: string, fileName: string, report?: CsvReportInfo): void {
  const body = csv.startsWith('\uFEFF') ? csv.slice(1) : csv;
  const text = report ? withCsvReportFrame(body, report) : body;
  const url = URL.createObjectURL(new Blob([`\uFEFF${text}`], { type: 'text/csv;charset=utf-8' }));
  const link = document.createElement('a');
  link.href = url;
  link.download = `${report ? reportFileName(fileName) : fileName.replace(/[^\w.-]+/g, '_')}.csv`;
  document.body.appendChild(link);
  link.click();
  link.remove();
  URL.revokeObjectURL(url);
}

/** The CSV table with the standard report header above it and the footer below it. */
export function withCsvReportFrame(tableCsv: string, report: CsvReportInfo): string {
  const records = Math.max(0, tableCsv.trim().split(/\r?\n/).length - 1);
  const meta = metaOf(records, report.meta);
  const line = (label: string, value: unknown) => `${csvCell(label)},${csvCell(value)}`;
  const head = [
    line('Organization', meta.organization),
    line('Report', report.title),
    ...(report.subtitle ?? []).filter(Boolean).map((s, i) => line(i === 0 ? 'Details' : '', s)),
    line('Generated on', formatGeneratedAt(meta.generatedAt)),
    ...(meta.generatedBy ? [line('Generated by', meta.generatedBy)] : []),
    line('Records', meta.records),
    line('Source', PORTAL_NAME),
    '',
  ];
  const foot = ['', line('End of report', `${meta.records} record${meta.records === 1 ? '' : 's'}`), line('Note', REPORT_NOTICE)];
  return `${head.join('\r\n')}\r\n${tableCsv.replace(/\r?\n$/, '')}\r\n${foot.join('\r\n')}\r\n`;
}

/** One CSV cell; values a spreadsheet would run as formulas are prefixed with a quote. */
export function csvCell(value: unknown): string {
  let text = value === null || value === undefined ? '' : String(value);
  if (/^[=+\-@\t\r]/.test(text)) text = `'${text}`;
  return /[",\n\r]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
}

export function toCsvText(headers: string[], rows: unknown[][]): string {
  return `${[headers, ...rows].map((r) => r.map(csvCell).join(',')).join('\r\n')}\r\n`;
}

import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';

export interface HRMSFilterTag {
  label: string;
  value: string;
}

export interface HRMSExportColumn {
  header: string;
  key: string;
  width?: number; // mm width for PDF
  align?: 'left' | 'center' | 'right';
  format?: (value: any, row: any) => string;
}

export interface HRMSExportOptions {
  title: string;
  subtitle?: string;
  category?: string;
  institution?: string;
  generatedBy?: {
    name: string;
    designation?: string;
    department?: string;
    email?: string;
  };
  filters: HRMSFilterTag[];
  summaryItems?: Array<{ label: string; value: string | number }>;
  columns: HRMSExportColumn[];
  data: any[];
  fileName: string;
  orientation?: 'portrait' | 'landscape';
  pdfThemeColor?: [number, number, number];
  confidentialNotice?: string;
}

/**
 * Universal HRMS CSV Exporter
 * Formats report with:
 * - Top metadata header (Institution, Report Name, Category, Generation Timestamp, Generated By)
 * - Active Filter & Selector Parameter block
 * - Summary Metrics block
 * - Clean CSV data rows
 * - Footer summary & confidentiality notice
 */
export const exportHRMSToCSV = (options: HRMSExportOptions): void => {
  const {
    title,
    subtitle,
    institution = 'WILDLIFE INSTITUTE OF INDIA (WII)',
    category = 'Human Resource Management System (HRMS) • LAMS 2.0',
    generatedBy,
    filters = [],
    summaryItems = [],
    columns,
    data,
    fileName,
    confidentialNotice = 'Confidential • Computer-generated Report for Official Use Only • Wildlife Institute of India'
  } = options;

  const now = new Date();
  const timestampStr = now.toLocaleDateString('en-IN', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit'
  });

  const escapeCSV = (val: any): string => {
    if (val === null || val === undefined) return '""';
    const s = String(val).replace(/"/g, '""');
    return `"${s}"`;
  };

  const csvLines: string[] = [];

  // 1. INSTITUTIONAL & REPORT HEADER BLOCK
  csvLines.push(`${escapeCSV('ORGANIZATION:')},${escapeCSV(institution)}`);
  csvLines.push(`${escapeCSV('REPORT TITLE:')},${escapeCSV(title)}`);
  if (subtitle) {
    csvLines.push(`${escapeCSV('DESCRIPTION:')},${escapeCSV(subtitle)}`);
  }
  csvLines.push(`${escapeCSV('MODULE / SYSTEM:')},${escapeCSV(category)}`);
  csvLines.push(`${escapeCSV('GENERATED ON:')},${escapeCSV(timestampStr)}`);
  if (generatedBy) {
    const byStr = `${generatedBy.name}${generatedBy.designation ? ` (${generatedBy.designation})` : ''}${generatedBy.department ? ` - ${generatedBy.department}` : ''}`;
    csvLines.push(`${escapeCSV('GENERATED BY:')},${escapeCSV(byStr)}`);
  }

  // 2. ACTIVE SELECTORS & FILTERS BLOCK
  if (filters.length > 0) {
    const activeFilters = filters
      .filter((f) => f.value && f.value !== 'all' && f.value !== 'All')
      .map((f) => `${f.label}: ${f.value}`);
    const filterText = activeFilters.length > 0 ? activeFilters.join(' | ') : 'All Records (No Restrictive Filters)';
    csvLines.push(`${escapeCSV('APPLIED FILTERS / SELECTORS:')},${escapeCSV(filterText)}`);
  } else {
    csvLines.push(`${escapeCSV('APPLIED FILTERS / SELECTORS:')},${escapeCSV('None (All Records)')}`);
  }

  // 3. SUMMARY METRICS BLOCK
  if (summaryItems.length > 0) {
    const summaryText = summaryItems.map((s) => `${s.label}: ${s.value}`).join(' | ');
    csvLines.push(`${escapeCSV('SUMMARY METRICS:')},${escapeCSV(summaryText)}`);
  }
  csvLines.push(`${escapeCSV('TOTAL RECORDS:')},${escapeCSV(data.length)}`);

  // Empty divider row
  csvLines.push('');

  // 4. TABULAR DATA HEADERS
  const headerRow = columns.map((col) => escapeCSV(col.header)).join(',');
  csvLines.push(headerRow);

  // 5. TABULAR DATA ROWS
  data.forEach((row, idx) => {
    const rowValues = columns.map((col) => {
      let val = row[col.key];
      if (col.format) {
        val = col.format(val, row);
      } else if (col.key === 'sno' || col.key === '#') {
        val = idx + 1;
      }
      return escapeCSV(val ?? '-');
    });
    csvLines.push(rowValues.join(','));
  });

  // 6. FOOTER BLOCK
  csvLines.push('');
  csvLines.push(`${escapeCSV('--- END OF REPORT ---')},${escapeCSV(`Total ${data.length} records exported successfully`)}`);
  csvLines.push(`${escapeCSV('NOTICE:')},${escapeCSV(confidentialNotice)}`);

  // UTF-8 BOM encoding for Excel compatibility
  const csvContent = '\uFEFF' + csvLines.join('\r\n');
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  const safeName = (fileName || title).replace(/[^a-zA-Z0-9_-]/g, '_');
  link.download = `${safeName}.csv`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
};

/**
 * Universal HRMS PDF Exporter
 * Formats report with:
 * - Institutional Navy Header Banner
 * - Report Title & Category Sub-banner
 * - Selector & Filter Parameters Context Box
 * - Crisp AutoTable with alternating row shading & custom column widths
 * - Running Page-numbered Institutional Footer on every page ("Page X of Y")
 */
export const exportHRMSToPDF = (options: HRMSExportOptions): void => {
  const {
    title,
    institution = 'WILDLIFE INSTITUTE OF INDIA (WII)',
    category = 'Human Resource Management System (HRMS) • LAMS 2.0',
    generatedBy,
    filters = [],
    columns,
    data,
    fileName,
    orientation = 'landscape',
    pdfThemeColor = [15, 23, 42] // Slate-900
  } = options;

  const doc = new jsPDF({
    orientation,
    unit: 'mm',
    format: 'a4'
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 14;

  const now = new Date();
  const timestampStr = now.toLocaleDateString('en-IN', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit'
  });

  // 1. TOP HEADER BANNER
  const bannerHeight = 22;
  doc.setFillColor(pdfThemeColor[0], pdfThemeColor[1], pdfThemeColor[2]);
  doc.rect(0, 0, pageWidth, bannerHeight, 'F');

  // Institution title
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(10.5);
  doc.setFont('helvetica', 'bold');
  doc.text(institution, margin, 8);

  // Report title
  doc.setFontSize(12.5);
  doc.setFont('helvetica', 'bold');
  doc.text(title.toUpperCase(), margin, 15);

  // Top-right category and date
  doc.setFontSize(8);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(203, 213, 225); // slate-300
  doc.text(category, pageWidth - margin, 8, { align: 'right' });
  doc.text(`Exported: ${timestampStr}`, pageWidth - margin, 15, { align: 'right' });

  // 2. CONTEXT & APPLIED FILTERS / SELECTORS BOX
  const filterBoxY = bannerHeight + 3.5;
  
  const filterPairs: string[] = [];
  filters.forEach((f) => {
    if (f.value && f.value !== 'all' && f.value !== 'All') {
      filterPairs.push(`${f.label}: ${f.value}`);
    } else {
      filterPairs.push(`${f.label}: All`);
    }
  });

  const isMultiLineFilters = filterPairs.length > 3;
  const filterBoxHeight = isMultiLineFilters ? 19 : 14;

  doc.setFillColor(248, 250, 252); // slate-50
  doc.rect(margin, filterBoxY, pageWidth - margin * 2, filterBoxHeight, 'F');
  doc.setDrawColor(226, 232, 240); // slate-200
  doc.rect(margin, filterBoxY, pageWidth - margin * 2, filterBoxHeight, 'S');

  // Left column: User & Total Count
  doc.setTextColor(15, 23, 42); // slate-900
  doc.setFontSize(8);
  doc.setFont('helvetica', 'bold');
  const genName = generatedBy ? `${generatedBy.name}${generatedBy.designation ? ` (${generatedBy.designation})` : ''}` : 'Official User';
  doc.text(`Generated By: ${genName}`, margin + 3, filterBoxY + 5);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7.5);
  doc.setTextColor(71, 85, 105);
  const deptStr = generatedBy?.department ? `Dept: ${generatedBy.department}  •  ` : '';
  doc.text(`${deptStr}Total Records Exported: ${data.length}`, margin + 3, filterBoxY + 10);

  // Right column: Applied Selectors
  const colRightX = margin + (pageWidth - margin * 2) * 0.44;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(7.5);
  doc.setTextColor(30, 41, 59);
  doc.text('Applied Selectors & Filters:', colRightX, filterBoxY + 5);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7);
  doc.setTextColor(71, 85, 105);
  const filterLine1 = filterPairs.slice(0, 3).join('  •  ') || 'None (Showing all records)';
  doc.text(filterLine1, colRightX, filterBoxY + 9.5);

  if (isMultiLineFilters) {
    const filterLine2 = filterPairs.slice(3, 7).join('  •  ');
    doc.text(filterLine2, colRightX, filterBoxY + 14.5);
  }

  // 3. TABLE BODY & COLUMNS
  const tableHead = [columns.map((c) => c.header)];
  const tableBody = data.map((row, idx) => {
    return columns.map((col) => {
      let val = row[col.key];
      if (col.format) {
        val = col.format(val, row);
      } else if (col.key === 'sno' || col.key === '#') {
        val = String(idx + 1);
      }
      return val !== null && val !== undefined ? String(val) : '-';
    });
  });

  const colStyles: Record<number, any> = {};
  columns.forEach((col, idx) => {
    colStyles[idx] = {
      halign: col.align || 'left',
      ...(col.width ? { cellWidth: col.width } : {})
    };
  });

  const startTableY = filterBoxY + filterBoxHeight + 3.5;

  autoTable(doc, {
    startY: startTableY,
    head: tableHead,
    body: tableBody,
    theme: 'grid',
    margin: { left: margin, right: margin, bottom: 16 },
    headStyles: {
      fillColor: [30, 41, 59], // Slate-800
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      fontSize: 7.5,
      cellPadding: 2
    },
    bodyStyles: {
      fontSize: 7,
      cellPadding: 1.8,
      textColor: [30, 41, 59],
      overflow: 'linebreak'
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252] // Slate-50 alternating
    },
    columnStyles: colStyles,
    didDrawPage: (hookData) => {
      // 4. RUNNING FOOTER ON EVERY PAGE
      const footerY = pageHeight - 7;

      // Divider line
      doc.setDrawColor(203, 213, 225); // Slate-300
      doc.line(margin, footerY - 3, pageWidth - margin, footerY - 3);

      // Left: Organization
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(6.5);
      doc.setTextColor(100, 116, 139); // Slate-500
      doc.text(
        'Wildlife Institute of India (WII) • An Autonomous Institution under MoEF&CC, Govt. of India',
        margin,
        footerY
      );

      // Center: Confidentiality notice
      doc.text(
        'Confidential • Official HRMS Document',
        pageWidth / 2,
        footerY,
        { align: 'center' }
      );

      // Right: Page number
      const pageStr = `Page ${hookData.pageNumber}`;
      doc.text(pageStr, pageWidth - margin, footerY, { align: 'right' });
    }
  });

  // Calculate total pages and update running footer page numbers: "Page X of Y"
  const totalPages = (doc.internal as any).getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(6.5);
    doc.setTextColor(100, 116, 139);
    // Erase right footer placeholder box and write "Page i of totalPages"
    doc.setFillColor(255, 255, 255);
    doc.rect(pageWidth - margin - 22, pageHeight - 9.5, 24, 5, 'F');
    doc.text(`Page ${i} of ${totalPages}`, pageWidth - margin, pageHeight - 7, { align: 'right' });
  }

  const safeName = (fileName || title).replace(/[^a-zA-Z0-9_-]/g, '_');
  doc.save(`${safeName}.pdf`);
};

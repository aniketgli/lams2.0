import { describe, expect, test } from 'bun:test';
import { buildTablePdf, reportFileName, setExportContext, toCsvText, withCsvReportFrame } from '../../src/shared/services/printTable';

describe('standard report files', () => {
  const at = new Date(2026, 10, 15, 14, 5);

  test('file names: WII_ prefix, safe characters, download time', () => {
    expect(reportFileName('WII_Leave_2026-01-01_to_2026-12-31', at)).toBe('WII_Leave_2026-01-01_to_2026-12-31_2026-11-15_1405');
    expect(reportFileName('Holiday Calendar 2026', at)).toBe('WII_Holiday_Calendar_2026_2026-11-15_1405');
    expect(reportFileName('../../etc/passwd', at)).toBe('WII_etc_passwd_2026-11-15_1405');
    expect(reportFileName('', at)).toBe('WII_Report_2026-11-15_1405');
  });

  test('CSV reports carry the header (organization, report, filters, generated on / by, records) and the footer', () => {
    setExportContext({ organization: 'Wildlife Institute of India', generatedBy: 'Aniket (0001) · Administrator' });
    const csv = withCsvReportFrame(toCsvText(['Date', 'Holiday'], [['26 Jan 2026', 'Republic Day'], ['15 Aug 2026', 'Independence Day']]),
      { title: 'Holiday Calendar 2026', subtitle: ['Type: Gazetted'], meta: { generatedAt: at } });
    const lines = csv.split('\r\n');
    expect(lines[0]).toBe('Organization,Wildlife Institute of India');
    expect(lines[1]).toBe('Report,Holiday Calendar 2026');
    expect(lines[2]).toBe('Details,Type: Gazetted');
    expect(lines[3]).toMatch(/^Generated on,"?15 Nov 2026/);
    expect(lines[4]).toBe('Generated by,Aniket (0001) · Administrator');
    expect(lines[5]).toBe('Records,2');
    expect(csv).toContain('Date,Holiday\r\n26 Jan 2026,Republic Day\r\n15 Aug 2026,Independence Day\r\n\r\nEnd of report,2 records');
    expect(lines.at(-2)).toMatch(/^Note,Computer-generated report/);
  });

  test('a value that starts like a formula cannot run in Excel', () => {
    const csv = withCsvReportFrame(toCsvText(['Name'], [['=HYPERLINK("http://evil")']]), { title: 'T' });
    expect(csv).toContain(`"'=HYPERLINK(""http://evil"")"`);
  });

  test('PDF reports build with the header details and page numbers, also with no rows', () => {
    const doc = buildTablePdf({ title: 'Leave requests', subtitle: ['Period: 2026'], headers: ['A', 'B'], rows: [], meta: { generatedAt: at, generatedBy: 'X (0001) · User' } });
    expect(doc.getNumberOfPages()).toBe(1);
    const many = buildTablePdf({ title: 'Leave requests', headers: ['A', 'B'], rows: Array.from({ length: 200 }, (_, i) => [i, 'row']) });
    expect(many.getNumberOfPages()).toBeGreaterThan(2);
  });
});

describe('server CSV downloads', () => {
  test('report title comes from the file name', async () => {
    const { titleFromFileName } = await import('../lib/csvResponse');
    expect(titleFromFileName('WII_Employee_Directory_2026-11-15.csv')).toBe('Employee Directory');
    expect(titleFromFileName('WII_Leave_Activity_Log_2026-11-15.csv')).toBe('Leave Activity Log');
  });
});
